export const HA_LinkedDropdownItem = ({
  className,
  inset,
  variant = "default",
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Item> & {
  inset?: boolean;
  variant?: "default" | "destructive";
  href: string;
  title: string;
  value?: string;
  type?: string;
}) => {
  const { href, title, value, ...rest } = props;
  const lenis = useLenis();
  const router = useTransitionRouter();
  const setOpen = useRPStore((store) => store.setDropdownOpen);
  const url = useVoyageur((l) => l.url);
  const pathName = useVoyageur((l) => l.pathName);
  const isAnchor = href === url || href.startsWith(`${pathName}#`);
  const handleClick = () => {
    setOpen(false);
    if (isAnchor) {
      lenis && lenis.scrollTo(href);
    } else {
      router.push(href);
    }
  };
  return (
    <HA_DropdownMenuItem
      data-themed={"background-color,color"}
      data-slot="dropdown-menu-item"
      data-inset={inset}
      data-variant={variant}
      className={HA_cn(
        "relative flex items-center gap-2 rounded-sm px-2 py-1.5 text-sm outline-hidden transition-colors ease-in-out select-none focus:bg-accent focus:text-accent-foreground data-[disabled]:pointer-events-none data-[disabled]:opacity-50 data-[inset]:pl-8 data-[variant=destructive]:text-destructive data-[variant=destructive]:focus:bg-destructive/10 data-[variant=destructive]:focus:text-destructive dark:data-[variant=destructive]:focus:bg-destructive/20 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 [&_svg:not([class*='text-'])]:text-muted-foreground data-[variant=destructive]:*:[svg]:!text-destructive",
        className
      )}
      value={value ?? href}
      onSelect={handleClick}
      {...props}
    >
      {title}
      {rest.children}
      {rest.type && (
        <div className="rp_tag absolute right-2">
          {rest.type.endsWith("s") ? rest.type.slice(0, -1) : rest.type}
        </div>
      )}
    </HA_DropdownMenuItem>
  );
};

